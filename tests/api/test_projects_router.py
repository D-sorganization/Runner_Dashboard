def test_charter_contract_pinned() -> None:
    """Mirrors Repository_Management shared_scripts/project_charter.py; change both or neither."""
    assert charter.FEATURE_COLUMNS == ("ID", "Feature", "Status", "Tracking", "Notes")
    assert charter.VALID_STATUSES == frozenset({"planned", "in-progress", "shipped", "parked"})
    assert charter.REQUIRED_SECTIONS == ("End goal", "Non-goals", "Features")
    assert charter.STATUS_HEADER == "<!-- generated by project-steward; do not hand-edit -->"


def test_parse_charter_and_progress() -> None:
    features = charter.parse_charter(CHARTER)
    assert [f.id for f in features] == ["F1", "F2", "F3", "F4"]
    first = {"id": "F1", "feature": "Parser", "status": "shipped", "tracking": "#1", "notes": "done"}
    assert features[0].to_dict() == first
    assert charter.feature_progress(features) == {
        "planned": 1,
        "in_progress": 1,
        "shipped": 1,
        "parked": 1,
        "percent_shipped": 25,
    }


def test_parse_charter_rejects_bad_status_and_columns() -> None:
    with pytest.raises(charter.CharterError, match="invalid status 'done'"):
        charter.parse_charter(CHARTER.replace("| shipped     |", "| done        |"))
    with pytest.raises(charter.CharterError, match="columns"):
        charter.parse_charter(CHARTER.replace("| Tracking |", "| Issue    |"))
    assert charter.validate_charter(CHARTER) == []


def test_parse_decisions_needed() -> None:
    assert charter.parse_decisions_needed(STATUS) == ["Adopt the charter contract fleet-wide?", "Park F4 permanently"]
    assert charter.parse_decisions_needed(STATUS.replace("- Adopt", "- None recorded.\n- Adopt")) == [
        "Adopt the charter contract fleet-wide?",
        "Park F4 permanently",
    ]
    assert charter.parse_decisions_needed("# nothing here") == []


