def _contents(text: str) -> dict[str, Any]:
    return {"content": base64.b64encode(text.encode("utf-8")).decode("ascii"), "encoding": "base64"}


def _run(run_id: str, role: str, repo: str, **fields: Any) -> store_mod.RunRecord:
    base: dict[str, Any] = {
        "provider": "claude",
        "model": None,
        "machine": "m",
        "target_kind": "prompt",
        "target_ref": "",
        "prompt": "p",
    }
    return store_mod.RunRecord(id=run_id, role=role, repo=repo, **{**base, **fields})


def _fake_gh(files: dict[str, str]) -> Any:
    """A ``gh_api`` stand-in serving ``{"<repo>/<path>": text}``; anything else is a 404."""

    async def fake(endpoint: str) -> dict[str, Any]:
        for key, text in files.items():
            repo, path = key.split("/", 1)
            if endpoint == f"/repos/{service.ORG}/{repo}/contents/{path}":
                return _contents(text)
        raise HTTPException(status_code=404, detail=f"GitHub resource not found: {endpoint}")

    return fake


