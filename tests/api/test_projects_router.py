async def test_build_project_charter_present(projects_env: Path) -> None:  # noqa: ARG001
    fake = _fake_gh({"Alpha/docs/project/CHARTER.md": CHARTER, "Alpha/docs/project/STATUS.md": STATUS})
    result = await service.build_project("Alpha", fetch=fake)
    assert result["charter_present"] is True
    assert result["status_present"] is True
    assert result["progress"]["percent_shipped"] == 25
    assert [f["id"] for f in result["features"]] == ["F1", "F2", "F3", "F4"]
    assert result["decisions_needed"] == ["Adopt the charter contract fleet-wide?", "Park F4 permanently"]
    assert result["last_steward_run"] is None
    assert "error" not in result


