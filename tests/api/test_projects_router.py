def test_overview_is_cached_but_steward_run_is_live(client: TestClient, monkeypatch: pytest.MonkeyPatch) -> None:
    calls: list[str] = []
    inner = _fake_gh({"Alpha/docs/project/CHARTER.md": CHARTER})

    async def counting(endpoint: str) -> dict[str, Any]:
        calls.append(endpoint)
        return await inner(endpoint)

    monkeypatch.setattr(service, "gh_api", counting)
    assert client.get("/api/projects/Alpha").json()["last_steward_run"] is None
    first_calls = len(calls)
    assert first_calls == 2  # charter + status
    store_mod.get_store().create_run(_run("r9", "project-steward", "Alpha"))
    again = client.get("/api/projects/Alpha").json()
    assert again["last_steward_run"]["id"] == "r9"
    assert again["charter_present"] is True
    assert len(calls) == first_calls  # served from cache
