def test_list_projects_route(client: TestClient, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(service, "gh_api", _fake_gh({"Alpha/docs/project/CHARTER.md": CHARTER}))
    resp = client.get("/api/projects")
    assert resp.status_code == 200, resp.text
    body = resp.json()
    assert body["count"] == 2 and [p["repo"] for p in body["projects"]] == ["Alpha", "Beta"]
    alpha, beta = body["projects"]
    assert alpha["charter_present"] is True and alpha["progress"]["shipped"] == 1
    assert beta["charter_present"] is False and "error" not in beta
    assert body["cache_ttl_seconds"] == 600.0


