def test_last_steward_run_picks_newest_for_repo(projects_env: Path) -> None:  # noqa: ARG001
    store = store_mod.get_store()
    store.create_run(_run("r1", "project-steward", "Alpha", created_at="2026-09-21T00:00:00Z"))
    store.create_run(_run("r2", "project-steward", "Alpha", status="succeeded", created_at="2026-09-22T00:00:00Z"))
    store.create_run(_run("r3", "night-watch", "Alpha", created_at="2026-09-23T00:00:00Z"))
    store.create_run(_run("r4", "project-steward", "Beta", created_at="2026-09-23T00:00:00Z"))
    run = service.last_steward_run("Alpha", store)
    assert run is not None and run["id"] == "r2" and run["status"] == "succeeded"
    assert service.last_steward_run("Gamma", store) is None


