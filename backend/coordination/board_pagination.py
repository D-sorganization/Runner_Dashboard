"""Board comment pagination and envelope parsing (issue #2824)."""

from __future__ import annotations

import json
import re
from collections.abc import Callable
from datetime import UTC, datetime
from typing import Any

BOARD_COMMENT_LIMIT = 1000
BOARD_PAGE_SIZE = 100
BOARD_MAX_PAGES = 100
SESSION_KEYS = ("session", "agent", "repo", "issue", "branch", "paths", "goals", "expires", "at")
BoardPageFetcher = Callable[[int, int], list[dict[str, Any]]]

_FOOTER = re.compile(r"\n\n---\n_Generated by \[Claude Code\]\(https://claude\.ai/code\)_\s*\Z")
_CTA_FOOTER = re.compile(r"\n*(<!--\s*fleet-CTA-footer\s*-->.*)\Z", re.DOTALL)
_CANONICAL_FENCE = re.compile(r"^<!--\s*agent-message\s+v1\s*-->\s*\n```json\s*\n(.*?)\n```$", re.DOTALL)
_LEGACY_FENCE = re.compile(r"^(?:<!--\s*agent-msg.*?\n)?```json\s+agent-msg\s*\n(.*?)\n```$", re.DOTALL)
_PREFIXES = ("<!-- agent-message", "<!--agent-message", "<!-- agent-msg", "<!--agent-msg", "```json agent-msg")


def _session(raw: dict[str, Any]) -> dict[str, Any]:
    return {**{k: raw.get(k) for k in SESSION_KEYS}, "source": "board"}


def _parse_comment_envelope(comment: dict[str, Any]) -> tuple[dict[str, Any] | None, str | None, str | None]:
    body = _CTA_FOOTER.sub("", _FOOTER.sub("", str(comment.get("body") or "").strip()).strip()).strip()
    if not body.startswith(_PREFIXES):
        return None, None, None
    user = (comment.get("user") or {}).get("login") if isinstance(comment.get("user"), dict) else None
    if not user:
        return None, None, "Rejected comment without verified GitHub user.login"
    match = _CANONICAL_FENCE.match(body) or _LEGACY_FENCE.match(body)
    if not match:
        return None, str(user), "Malformed coordination envelope"
    try:
        env = json.loads(match.group(1).strip())
    except Exception as exc:  # noqa: BLE001
        return None, str(user), f"Malformed coordination envelope: {exc}"
    req = ("session", "repo", "kind", "id")
    if not isinstance(env, dict) or not all(str(env.get(k) or "").strip() for k in req):
        return None, str(user), "Malformed coordination envelope: missing required fields"
    return env, str(user), None


def _validate_presence_expires(env: dict[str, Any], ref_now: datetime) -> tuple[bool, str | None]:
    if env.get("kind") != "presence":
        return False, None
    exp_raw, sess = str(env.get("expires") or "").strip(), env.get("session")
    if not exp_raw:
        return False, f"Invalid or missing expires timestamp for presence {sess}"
    try:
        exp_dt = datetime.fromisoformat(exp_raw.replace("Z", "+00:00"))
        if exp_dt.utcoffset() is None:
            return False, f"Invalid naive expires timestamp for presence {sess}"
        return exp_dt > ref_now, None
    except Exception:  # noqa: BLE001
        return False, f"Invalid or missing expires timestamp for presence {sess}"


def _apply_event(
    env: dict[str, Any],
    author: str,
    unexpired: bool,
    owners: dict[str, tuple[str, str]],
    active: dict[str, dict[str, Any]],
    replay_warnings: list[str],
    rejected_by_session: dict[str, list[str]],
    live_conflicts: list[str],
) -> None:
    sess, repo, kind = str(env["session"]), str(env["repo"]), str(env["kind"])
    owner = (repo, author)
    if sess in owners and owners[sess] != owner:
        w = f"Rejected identity change for {sess}"
        replay_warnings.append(w)
        rejected_by_session.setdefault(sess, []).append(w)
        if (kind == "presence" and unexpired) or (kind in {"message", "release"} and sess in active):
            live_conflicts.append(w)
        return
    if kind == "presence":
        owners[sess] = owner
        if unexpired:
            active[sess] = _session(env)
        else:
            active.pop(sess, None)
    elif sess not in owners:
        w = f"Rejected unregistered sender {sess}"
        replay_warnings.append(w)
        rejected_by_session.setdefault(sess, []).append(w)
    elif kind == "release":
        active.pop(sess, None)


def _paginate_pages(
    fetch_page: BoardPageFetcher,
    per_page: int,
    max_pages: int,
    ref_now: datetime,
    owners: dict[str, tuple[str, str]],
    active: dict[str, dict[str, Any]],
    replay_warnings: list[str],
    rejected_by_session: dict[str, list[str]],
    live_conflicts: list[str],
    read_warnings: list[str],
) -> tuple[bool, int]:
    seen_ids: set[str] = set()
    total = 0
    for page in range(1, max(1, max_pages) + 1):
        try:
            batch = fetch_page(page, per_page)
        except Exception as exc:  # noqa: BLE001
            read_warnings.append(f"Board comment pagination failed on page {page}: {exc}")
            return False, total
        if not isinstance(batch, list):
            read_warnings.append(f"Board comment page {page} returned invalid payload")
            return False, total
        total += len(batch)
        for c in batch:
            if not isinstance(c, dict):
                continue
            env, author, err = _parse_comment_envelope(c)
            if err:
                read_warnings.append(err)
            elif env and author and str(env["id"]) not in seen_ids:
                seen_ids.add(str(env["id"]))
                unexp, exp_err = _validate_presence_expires(env, ref_now)
                if exp_err:
                    read_warnings.append(exp_err)
                else:
                    _apply_event(
                        env, author, unexp, owners, active, replay_warnings, rejected_by_session, live_conflicts
                    )
        if len(batch) < per_page:
            return True, total
    read_warnings.append(f"Board page limit ({max_pages} pages) reached; view is incomplete")
    return False, total


def paginate_board_comments(
    fetch_page: BoardPageFetcher,
    *,
    per_page: int = BOARD_PAGE_SIZE,
    max_pages: int = BOARD_MAX_PAGES,
    now: datetime | None = None,
) -> dict[str, Any]:
    """Paginate RM#2376 comments across all pages (>1,000 comments) and replay presence."""
    ref_now = now or datetime.now(UTC)
    active: dict[str, dict[str, Any]] = {}
    owners: dict[str, tuple[str, str]] = {}
    replay_warnings: list[str] = []
    rejected_by_session: dict[str, list[str]] = {}
    live_conflicts: list[str] = []
    read_warnings: list[str] = []

    pages_complete, total = _paginate_pages(
        fetch_page,
        per_page,
        max_pages,
        ref_now,
        owners,
        active,
        replay_warnings,
        rejected_by_session,
        live_conflicts,
        read_warnings,
    )
    for s in active:
        live_conflicts.extend(rejected_by_session.get(s, []))
    act_c = list(dict.fromkeys(live_conflicts))
    clean_rw = list(dict.fromkeys(read_warnings))
    clean_rep = list(dict.fromkeys(replay_warnings))
    return {
        "available": True,
        "complete": pages_complete and not clean_rw and not act_c,
        "pages_complete": pages_complete,
        "degraded_history": bool(clean_rep),
        "read_warnings": clean_rw,
        "replay_warnings": clean_rep,
        "active_conflicts": act_c,
        "comment_limit_exceeded": not pages_complete and total >= BOARD_COMMENT_LIMIT,
        "comment_count": total,
        "sessions": list(active.values()),
        "messages": [],
        "conflicts": [],
        "warnings": list(dict.fromkeys([*clean_rw, *clean_rep])),
    }


def _is_limit_warning(w: str) -> bool:
    return any(k in w.lower() for k in ("page limit", "comment limit", "comment-limit"))


def _merge_paginated(data: dict[str, Any], paginated: dict[str, Any]) -> dict[str, Any]:
    pages_complete = bool(paginated.get("pages_complete", paginated.get("complete", False)))
    dw, pw = data.get, paginated.get
    raw_rw = [str(w) for w in dw("read_warnings") or []]
    if "read_warnings" not in data and "replay_warnings" not in data and "active_conflicts" not in data:
        raw_rw.extend(str(w) for w in dw("warnings") or [])
    if pages_complete:
        raw_rw = [w for w in raw_rw if not _is_limit_warning(w)]
    read_w = list(dict.fromkeys([*raw_rw, *pw("read_warnings", [])]))
    rep_w = list(dict.fromkeys([*(str(w) for w in dw("replay_warnings") or []), *pw("replay_warnings", [])]))
    act_c = list(dict.fromkeys([*(str(w) for w in dw("active_conflicts") or []), *pw("active_conflicts", [])]))
    sessions = (
        pw("sessions", []) if pages_complete else [_session(s) for s in dw("sessions") or [] if isinstance(s, dict)]
    )

    return {
        "available": True,
        "complete": pages_complete and not act_c and not read_w,
        "degraded_history": bool(pw("degraded_history")) or bool(rep_w),
        "read_warnings": read_w,
        "replay_warnings": rep_w,
        "active_conflicts": act_c,
        "comment_limit_exceeded": not pages_complete,
        "comment_count": pw("comment_count", dw("comment_count", 0)),
        "sessions": sessions,
        "messages": list(dw("messages") or []),
        "conflicts": list(dw("conflicts") or []),
        "warnings": list(dict.fromkeys([*read_w, *rep_w])),
    }
