"""Board comment pagination and envelope parsing (issue #2824)."""

from __future__ import annotations

import json
import re
from collections.abc import Callable
from datetime import UTC, datetime, timedelta
from typing import Any

from coordination.gh_cli import gh_api_json
from staff.workspace import rm_root

BOARD_COMMENT_LIMIT, BOARD_PAGE_SIZE, BOARD_MAX_PAGES = 1000, 100, 100
SESSION_KEYS = ("session", "agent", "repo", "issue", "branch", "paths", "goals", "expires", "at")
BoardPageFetcher = Callable[[int, int], list[dict[str, Any]]]
_ID, _REPO_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,127}\Z"), re.compile(r"(?:[A-Za-z0-9-]{1,39}/)?[A-Za-z0-9][A-Za-z0-9_.-]{0,127}\Z")  # noqa: E501  # fmt: skip
_FOOTER = re.compile(r"\n*(?:---\n_Generated by \[Claude Code\].*|<!--\s*fleet-CTA-footer\s*-->.*)\s*\Z", re.DOTALL)
_FENCE = re.compile(r"^(?:<!--\s*(?:agent-message\s+v1|agent-msg.*?)\s*-->\s*\n)?```(?:json\s+agent-msg|json)\s*\n(.*?)\n```$", re.DOTALL)  # noqa: E501  # fmt: skip
_PREFIXES = ("<!-- agent-message", "<!--agent-message", "<!-- agent-msg", "<!--agent-msg", "```json agent-msg")


def _session(raw: dict[str, Any]) -> dict[str, Any]:
    return {**{k: raw.get(k) for k in SESSION_KEYS}, "source": "board"}


def _validate_presence(env: dict[str, Any], at_dt: datetime) -> str | None:
    iss, br, pths, g, ag = env.get("issue"), env.get("branch"), env.get("paths"), env.get("goals"), env.get("agent")
    if not isinstance(ag, str) or not ag.strip() or type(iss) is not int or iss <= 0 or not isinstance(br, str) or not (0 < len(br.strip()) <= 250):  # noqa: E501  # fmt: skip
        return "Invalid presence agent, issue, or branch"
    if not isinstance(pths, list) or len(pths) > 64 or not all(isinstance(p, str) and 0 < len(p.strip()) <= 300 and not any(c in p for c in "\\:*?[]") and not any(x in {"", ".", ".."} for x in p.split("/")) for p in pths):  # noqa: E501  # fmt: skip
        return "Paths must be a bounded list of normalized relative paths"
    if g is not None and (not isinstance(g, dict) or len(g) > 64 or not all(isinstance(k, str) and _ID.fullmatch(k) and isinstance(v, str) and 0 < len(v.strip()) <= 250 for k, v in g.items())):  # noqa: E501  # fmt: skip
        return "Goals must map bounded keys to bounded outcomes"
    try:
        exp = datetime.fromisoformat(str(env.get("expires")).replace("Z", "+00:00"))
        return None if exp.utcoffset() == timedelta(0) and (timedelta(0) < exp - at_dt <= timedelta(hours=8)) else "Invalid TTL"  # noqa: E501  # fmt: skip
    except Exception:  # noqa: BLE001
        return "Invalid expires timestamp"


def _validate_envelope(env: Any) -> str | None:
    if not isinstance(env, dict) or type(env.get("version")) is not int or env.get("version") != 1:
        return "Unsupported coordination event version"
    for k, pat in (("id", _ID), ("session", _ID), ("repo", _REPO_RE)):
        if not isinstance(env.get(k), str) or not pat.fullmatch(str(env.get(k))):
            return f"Invalid or unbounded identifier: {k}"
    at_raw, kind = env.get("at"), env.get("kind")
    if kind not in {"presence", "message", "ack", "release"}:
        return f"Unknown coordination event kind: {kind}"
    try:
        at_dt = datetime.fromisoformat(str(at_raw).replace("Z", "+00:00"))
        if at_dt.utcoffset() != timedelta(0):
            return "Timestamp must include UTC offset"
    except Exception:  # noqa: BLE001
        return "Invalid UTC timestamp in envelope"
    if kind == "presence":
        return _validate_presence(env, at_dt)
    if kind == "message":
        txt, rec = env.get("text"), env.get("recipient")
        if not isinstance(txt, str) or not (0 < len(txt.strip()) <= 4000) or any(ord(c) < 32 and c not in "\n\t" for c in txt):  # noqa: E501  # fmt: skip
            return "Expected nonempty bounded text without control characters"
        return None if isinstance(rec, str) and (rec == "*" or bool(_ID.fullmatch(rec))) else "Invalid recipient"
    if kind == "ack" and (not isinstance(env.get("message_id"), str) or not _ID.fullmatch(str(env.get("message_id")))):
        return "Invalid ack message_id"
    return None


def _parse_comment_envelope(comment: dict[str, Any]) -> tuple[dict[str, Any] | None, str | None, str | None]:
    body = _FOOTER.sub("", str(comment.get("body") or "").strip()).strip()
    if not body.startswith(_PREFIXES):
        return None, None, None
    user = (comment.get("user") or {}).get("login") if isinstance(comment.get("user"), dict) else None
    if not user:
        return None, None, "Rejected comment without verified GitHub user.login"
    if not (m := _FENCE.match(body)):
        return None, str(user), "Malformed coordination envelope"
    try:
        env = json.loads(m.group(1).strip())
    except Exception as exc:  # noqa: BLE001
        return None, str(user), f"Malformed coordination envelope: {exc}"
    err = _validate_envelope(env)
    return (None, str(user), f"Invalid coordination envelope: {err}") if err else (env, str(user), None)


def _apply_event(env: dict[str, Any], author: str, ref_now: datetime, st: dict[str, Any]) -> None:
    sess, repo, kind, owner = str(env["session"]), str(env["repo"]), str(env["kind"]), (str(env["repo"]), author)
    owners, active, messages, acks = st["owners"], st["active"], st["messages"], st["acks"]
    unexp = kind == "presence" and datetime.fromisoformat(str(env["expires"]).replace("Z", "+00:00")) > ref_now
    if sess in owners and owners[sess] != owner:
        st["replay_w"].append(w := f"Rejected identity change for {sess}")
        st["rejected"].setdefault(sess, []).append(w)
        if (kind == "presence" and unexp) or (kind in {"message", "ack", "release"} and sess in active):
            st["live_c"].append(w)
        return
    if kind == "presence":
        owners[sess] = owner
        if unexp:
            active[sess] = _session(env)
        else:
            active.pop(sess, None)
    elif sess not in owners:
        st["replay_w"].append(w := f"Rejected unregistered sender {sess}")
        st["rejected"].setdefault(sess, []).append(w)
    elif kind == "release":
        active.pop(sess, None)
    elif kind == "message":
        messages.append(env)
    elif kind == "ack":
        mid, r_cf = str(env.get("message_id") or ""), repo.casefold()
        for m in messages:
            if m.get("id") == mid and str(m.get("repo", "")).casefold() == r_cf and m.get("recipient") in {sess, "*"}:
                acks.add((sess, mid))


def default_board_page_fetcher(page: int, per_page: int) -> list[dict[str, Any]]:
    root, repo, issue, days, preds = rm_root(), "D-sorganization/Repository_Management", 2539, 3, []
    if root and (cfg := root / "config" / "agent_communication.json").is_file():
        try:
            c = json.loads(cfg.read_text(encoding="utf-8"))
            repo, issue = str(c.get("board_repo") or repo), int(c.get("board_issue") or issue)
            days, preds = int(c.get("board_window_days") or days), [int(p) for p in c.get("board_predecessors") or []]
        except Exception:  # noqa: BLE001
            pass
    if page == 0:
        since_p, res = (datetime.now(UTC) - timedelta(hours=8)).strftime("%Y-%m-%dT%H:%M:%SZ"), []
        for p in preds[-3:]:
            try:
                b = gh_api_json(f"/repos/{repo}/issues/{p}/comments?per_page=100&since={since_p}")
                res.extend(b if isinstance(b, list) else [])
            except Exception:  # noqa: BLE001
                pass
        return res
    since = (datetime.now(UTC) - timedelta(days=days)).strftime("%Y-%m-%dT%H:%M:%SZ")
    data = gh_api_json(f"/repos/{repo}/issues/{issue}/comments?per_page={per_page}&page={page}&since={since}")
    return data if isinstance(data, list) else []


def _is_replay_warning(w: str) -> str | None:
    for p in ("Rejected identity change for ", "Rejected unregistered sender "):
        if w.startswith(p):
            return w[len(p) :].strip()
    return None


def _paginate_pages(
    fetch_page: BoardPageFetcher, per_page: int, max_pages: int, ref_now: datetime, st: dict[str, Any]
) -> tuple[bool, int]:
    seen, total, pages = set(), 0, [0] if fetch_page is default_board_page_fetcher else []
    pages.extend(range(1, max(1, max_pages) + 1))
    for page in pages:
        try:
            batch = fetch_page(page, per_page)
        except Exception as exc:  # noqa: BLE001
            if page > 0:
                st["read_w"].append(f"Board comment pagination failed on page {page}: {exc}")
                return False, total
            continue
        if not isinstance(batch, list):
            if page > 0:
                st["read_w"].append(f"Board comment page {page} returned invalid payload")
                return False, total
            continue
        total += len(batch) if page > 0 else 0
        for c in batch:
            if isinstance(c, dict):
                env, author, err = _parse_comment_envelope(c)
                if err:
                    st["read_w"].append(err)
                elif env and author and (eid := str(env["id"])) not in seen:
                    seen.add(eid)
                    _apply_event(env, author, ref_now, st)
        if page > 0 and len(batch) < per_page:
            return True, total
    st["read_w"].append(f"Board page limit ({max_pages} pages) reached; view is incomplete")
    return False, total


def _conflicts_for(s: str, active: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    if not (own := active.get(s)):
        return []
    res, own_repo = [], str(own.get("repo", "")).casefold()
    for k, oth in active.items():
        if k == s or str(oth.get("repo", "")).casefold() != own_repo:
            continue
        p = [f"{a} ↔ {b}" for a in own.get("paths") or [] for b in oth.get("paths") or [] if (ac := a.casefold()) == (bc := b.casefold()) or ac.startswith(bc + "/") or bc.startswith(ac + "/")]  # noqa: E501  # fmt: skip
        og = oth.get("goals") or {}
        g = [f"{gk}: {gv} ↔ {og[gk]}" for gk, gv in (own.get("goals") or {}).items() if gk in og and gv != og[gk]]
        if p or g:
            res.append({"session": k, "agent": oth.get("agent"), "issue": oth.get("issue"), "branch": oth.get("branch"), "paths": p, "goals": g})  # noqa: E501  # fmt: skip
    return res


def _filter_coordination(
    session: str | None, active: dict[str, dict[str, Any]], messages: list[dict[str, Any]], acks: set[tuple[str, str]]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    if session is not None:
        own_repo = str(active[session].get("repo", "")).casefold() if session in active else None
        out_m = [m for m in messages if own_repo and str(m.get("repo", "")).casefold() == own_repo and m.get("session") != session and m.get("recipient") in {session, "*"} and (session, m.get("id")) not in acks]  # noqa: E501  # fmt: skip
        return out_m, _conflicts_for(session, active)
    out_m = [m for m in messages if m.get("recipient") == "*" or (m.get("recipient") in active and (m.get("recipient"), m.get("id")) not in acks)]  # noqa: E501  # fmt: skip
    raw_c = [c for s in active for c in _conflicts_for(s, active)]
    return out_m, [c for i, c in enumerate(raw_c) if c not in raw_c[:i]]


def paginate_board_comments(
    fetch_page: BoardPageFetcher, *, per_page: int = BOARD_PAGE_SIZE, max_pages: int = BOARD_MAX_PAGES,
    now: datetime | None = None, session: str | None = None,
) -> dict[str, Any]:  # fmt: skip
    """Paginate RM#2376 comments across all pages (>1,000 comments) and replay coordination."""
    st: dict[str, Any] = {
        "active": {}, "owners": {}, "messages": [], "acks": set(),
        "replay_w": [], "live_c": [], "read_w": [], "rejected": {},
    }  # fmt: skip
    done, total = _paginate_pages(fetch_page, per_page, max_pages, now or datetime.now(UTC), st)
    for s in st["active"]:
        st["live_c"].extend(st["rejected"].get(s, []))
    act_c = list(dict.fromkeys(st["live_c"]))
    rw, rep = list(dict.fromkeys(st["read_w"])), list(dict.fromkeys(st["replay_w"]))
    out_m, out_c = _filter_coordination(session, st["active"], st["messages"], st["acks"])
    return {
        "available": True, "complete": done and not rw and not act_c, "pages_complete": done,
        "degraded_history": bool(rep), "read_warnings": rw, "replay_warnings": rep, "active_conflicts": act_c,
        "comment_limit_exceeded": not done and total >= BOARD_COMMENT_LIMIT, "comment_count": total,
        "sessions": list(st["active"].values()), "messages": out_m, "conflicts": out_c,
        "warnings": list(dict.fromkeys([*rw, *rep])),
    }  # fmt: skip


def _merge_paginated(data: dict[str, Any], pag: dict[str, Any]) -> dict[str, Any]:
    done, pw = bool(pag.get("pages_complete", pag.get("complete", False))), pag.get
    sess = pw("sessions", []) if done else [_session(s) for s in data.get("sessions") or [] if isinstance(s, dict)]
    live_names = {str(s.get("session")) for s in sess if isinstance(s, dict)}
    raw_rw = [str(w) for w in data.get("read_warnings") or []]
    rep = [str(w) for w in data.get("replay_warnings") or []]
    act = [str(w) for w in data.get("active_conflicts") or []]
    if "read_warnings" not in data and "replay_warnings" not in data and "active_conflicts" not in data:
        for w in (str(x) for x in data.get("warnings") or []):
            if (r_sess := _is_replay_warning(w)) is not None:
                rep.append(w)
                if r_sess in live_names:
                    act.append(w)
            else:
                raw_rw.append(w)
    lim = ("page limit", "comment limit", "comment-limit")
    rw = [w for w in raw_rw if not (done and any(k in w.lower() for k in lim))] + list(pw("read_warnings", []))
    all_rw, all_rep = list(dict.fromkeys(rw)), list(dict.fromkeys(rep + list(pw("replay_warnings", []))))
    all_act = list(dict.fromkeys(act + list(pw("active_conflicts", []))))
    msgs = list(pw("messages", [])) or list(data.get("messages") or []) if done else list(data.get("messages") or [])
    confs = (
        list(pw("conflicts", [])) or list(data.get("conflicts") or []) if done else list(data.get("conflicts") or [])
    )  # noqa: E501  # fmt: skip
    return {
        "available": True, "complete": done and not all_act and not all_rw,
        "degraded_history": bool(pw("degraded_history")) or bool(all_rep),
        "read_warnings": all_rw, "replay_warnings": all_rep, "active_conflicts": all_act,
        "comment_limit_exceeded": not done, "comment_count": pw("comment_count", data.get("comment_count", 0)),
        "sessions": sess, "messages": msgs, "conflicts": confs,
        "warnings": list(dict.fromkeys([*all_rw, *all_rep])),
    }  # fmt: skip
